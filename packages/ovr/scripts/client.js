import { spawn } from "node:child_process";
import { watch } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";

// Generate a static browser asset before compilation. The server imports only this string.
const path = new URL("../src/auth/client.ts", import.meta.url);
async function generate() {
	const source = stripTypeScriptTypes(await readFile(path, "utf8"));
	await writeFile(
		new URL("../src/auth/client-source.ts", import.meta.url),
		`// Generated by scripts/client.js; edit client.ts instead.\nexport const source = ${JSON.stringify(source)};\n`,
	);
}
await generate();

if (process.argv.includes("--watch")) {
	const watcher = watch(path, () => {
		void generate().catch(console.error);
	});
	const compiler = spawn("tsc", ["--watch", "-p", "tsconfig.build.json"], {
		stdio: "inherit",
	});
	compiler.on("exit", (code) => {
		watcher.close();
		process.exitCode = code ?? 1;
	});
	for (const signal of ["SIGINT", "SIGTERM"])
		process.once(signal, () => {
			watcher.close();
			compiler.kill(signal);
		});
}
